#include "gpio_config.h"

/******************************************************************************
External declarations
-----------------------------------------------------------------------------*/

/******************************************************************************
Defines and macros
-----------------------------------------------------------------------------*/
#define    LED1_ON_TIME     (50) //10 * 10ms = 500ms
#define    LED1_OFF_TIME    (50) //10 * 10ms = 500ms
#define    LED1_PERIOD      (LED1_ON_TIME + LED1_OFF_TIME)

/******************************************************************************
Typedefs and structures
-----------------------------------------------------------------------------*/

/******************************************************************************
Global variable definitions
-----------------------------------------------------------------------------*/
Uint16 led_tick;

/******************************************************************************
Function prototypes
-----------------------------------------------------------------------------*/

/******************************************************************************
Function implementations
-----------------------------------------------------------------------------*/
/******************************************************************************
*Description:
*Input:
*Output:
-----------------------------------------------------------------------------*/
void GPIO_Init(void)
{
    EALLOW;

    LED1_SET_MUX = GPIO_IO_MODE;
    LED1_SET_PUD = GPIO_PULL_UP;
    LED1_SET_DIR = GPIO_OUTPUT;
    LED1_SET_HIGH();

    EDIS;

    led_tick = 0;
}

/******************************************************************************
*Description:LED闪烁函数放在10ms任务运行
-----------------------------------------------------------------------------*/
void LED_Task_Run(void)
{
    ++led_tick >= LED1_ON_TIME ? ((led_tick >= LED1_PERIOD) ? (led_tick = 0) : (LED1_SET_HIGH())) : (LED1_SET_LOW());
}
















