#define TIMEROUTSCI    5200 //估算的等待超时时间，请根据实际修改

//字符发送函数，阻塞发送
#define    Uart_Send_Char(data)             \
do{                                         \
    Uint32 WaitTimer;                       \
    WaitTimer = 0;                          \
    while(SciaRegs.SCICTL2.bit.TXEMPTY != 1)\
    {                                       \
        WaitTimer++;                        \
        if(WaitTimer > TIMEROUTSCI)break;   \
    }                                       \
    if(WaitTimer <= TIMEROUTSCI)            \
    {                                       \
        SciaRegs.SCITXBUF = data;           \
    }                                       \
}while(0)



